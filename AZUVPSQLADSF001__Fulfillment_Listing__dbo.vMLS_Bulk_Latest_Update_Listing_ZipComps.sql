Create VIEW [dbo].[vMLS_Bulk_Latest_Update_Listing_ZipComps]
AS
SELECT [Property Address]
	,[Property City]
	,[Property State]
	,[Property Zip]
	,[Property Zip + 4]
	,[Assessor's Parcel Identification Number]
	,RIGHT('00000' + CAST([County FIPS] AS VARCHAR(5)), 5) AS [County FIPS]
	,[Internal FA Property Ref ID]
	,[Property Type]
	,[Property Sub-Type]
	,[Lot Size (Sq Ft)]
	,[Home Size (Sq Ft)]
	,[Home or Building Style]
	,[Heating Type]
	,[Heating Fuel Type]
	,[Cooling Type]
	,[Cooling Fuel Type]
	,[Number of Stories]
	,[Year Built]
	,[Roof Type]
	,[Exterior Construction]
	,[Number of Bedrooms]
	,[Number of Bathrooms]
	,[Number of Garages]
	,[Garage Type]
	,[Pool Features]
	,[View Features]
	,[FA Initial List Date]
	,[FA Calculated Days on Market]
	,[Current Original Listing Date]
	,[Initial List Status]
	,[Listing Number]
	,[Status]
	,[Status Sub Type]
	,[Current Listing Price]
	,[Max List Price]
	,[Max List Price Date]
	,[Min List Price]
	,[Min List Price Date]
	,[Sold Price]
	,[Sold Date]
	,[FA Adjusted Sold Price]
	,[FA Sold Price Range]
	,[Last Listing Price Change Amount]
	,[Last Listing Price Change Date]
	,[Prior Listing Price Change Amount]
	,[Prior Listing Price Change Date]
	,[Last Listing Status Change]
	,[Last Listing Status Change Date]
	,[Last Listing Status Sub Type Change]
	,[Last Listing Status Sub Type Change Date]
	,[Prior Listing Status Change]
	,[Prior Listing Status Change Date]
	,[Prior Listing Status Sub Type Change]
	,[Prior Listing Status Sub Type Change Date]
	,[Listing Tracking ID]
	,[FA Unique Listing Identifier - Ref ID]
	,[Update Timestamp]
	,[Add, Change, Delete Indicator]
	,[Property Details]
	,ISNULL(agentstd.MLS_LISTING_AGENT_LICENSE_NBR, '') AS [Listing Agent License Number]
	,ISNULL(agentstd.MLS_LISTING_AGENT_NAME_nochar, '') AS [Listing Agent Name]
	,ISNULL(agentstd.MLS_LISTING_AGENT_ADDRESS, '') AS [Listing Agent Address]
	,ISNULL(agentstd.AGENT_PHONE, '') AS [Listing Agent Phone]
	,ISNULL(agentstd.MLS_LISTING_AGENT_EMAIL_STD, '') AS [Listing Agent Email]
	,ISNULL(officestd.Mls_Office_name_STD, '') AS [Office Name]
	,ISNULL(officestd.MLS_OFFICE_ADDRESS, '') AS [Office Address]
	,ISNULL(officestd.MLS_OFFICE_PHONE, '') AS [Office Phone]
	,ISNULL(officestd.MLS_OFFICE_EMAIL, '') AS [Office Email]
FROM Fulfillment_Listing.dbo.MLS_Bulk_Current_Listing(NOLOCK) a
LEFT JOIN Fulfillment_Listing.dbo.MLS_Listing_Agent(NOLOCK) agent ON agent.MLS_Listing_Agent_CODE = a.MLS_Listing_Agent_CODE
LEFT JOIN Fulfillment_Listing.dbo.MLS_Listing_Agent_Std(NOLOCK) agentstd ON agentstd.MLS_Listing_Agent_CODE_STD = agent.MLS_Listing_Agent_CODE_STD
LEFT JOIN Fulfillment_Listing.dbo.MLS_Office(NOLOCK) office ON office.MLS_OFFICE_CODE = a.MLS_OFFICE_CODE
LEFT JOIN Fulfillment_Listing.dbo.MLS_Office_Std(NOLOCK) officestd ON officestd.MLS_OFFICE_CODE_STD = office.MLS_OFFICE_CODE_STD
WHERE Latest_Update_Ind = 1

